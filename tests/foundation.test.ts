const directory = mkdtempSync(join(tmpdir(), "ahau-foundation-"));
process.env.DATABASE_PATH = join(directory, "archive.sqlite");
process.env.BETTER_AUTH_URL = "http://localhost:3000";
process.env.BETTER_AUTH_SECRET = randomBytes(48).toString("base64url");
const { db, sqlite } = openDatabase();
migrate(db, { migrationsFolder: "./drizzle" });

after(() => {
  getDb().$client.close();
  sqlite.close();
  rmSync(directory, { recursive: true, force: true });
});

function batch() {
  return db
    .insert(submissions)
    .values({ attribution: "Test author", contact: "private@example.invalid" })
    .returning()
    .get();
}

function photo(submissionId: string) {
  return {
    submissionId,
    title: "Test campus",
    originalKey: `private/${randomUUID()}`,
    mimeType: "image/jpeg",
    byteSize: 1024,
  };
}

test("migrations are repeatable and UUIDs are generated by the application", () => {
  migrate(db, { migrationsFolder: "./drizzle" });
  assert.match(batch().id, /^[0-9a-f-]{36}$/);
  assert.equal(sqlite.pragma("foreign_keys", { simple: true }), 1);
});

test("database rejects invalid status, missing public assets and orphaned photos", () => {
  const input = photo(batch().id);
  assert.throws(
    () =>
      sqlite
        .prepare(
          "INSERT INTO photos (id, submission_id, title, status, original_key, mime_type, byte_size, submitted_at, updated_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)",
        )
        .run(
          randomUUID(),
          input.submissionId,
          input.title,
          "invalid",
          input.originalKey,
          input.mimeType,
          input.byteSize,
          Date.now(),
          Date.now(),
        ),
    /CHECK/,
  );
  assert.throws(
    () =>
      db
        .insert(photos)
        .values({ ...input, status: "approved" })
        .run(),
    /CHECK/,
  );
  assert.throws(
    () => db.insert(photos).values(photo(randomUUID())).run(),
    /FOREIGN KEY/,
  );
});

test("public queries exclude pending, rejected and hidden photos and private fields", () => {
  const submissionId = batch().id;
  const approvedId = randomUUID();
  const approved = db
    .insert(photos)
    .values({
      ...photo(submissionId),
      id: approvedId,
      status: "approved",
      displayKey: `photos/${approvedId}/display.webp`,
      thumbnailKey: `photos/${approvedId}/thumbnail.webp`,
      publishedAt: new Date(),
    })
    .returning()
    .get();
  for (const status of ["pending", "rejected", "hidden"] as const) {
    const privatePhoto = db
      .insert(photos)
      .values({ ...photo(submissionId), status })
      .returning()
      .get();
    assert.equal(findPublicPhoto(privatePhoto.id), undefined);
  }
  const publicPhotos = listPublicPhotos();
  assert.deepEqual(
    publicPhotos.map((item) => item.id),
    [approved.id],
  );
  assert.equal("contact" in publicPhotos[0], false);
  assert.equal("originalKey" in publicPhotos[0], false);
  assert.equal("displayKey" in publicPhotos[0], false);
  db.update(photos)
    .set({ status: "hidden" })
    .where(eq(photos.id, approved.id))
    .run();
  assert.equal(findPublicPhoto(approved.id), undefined);
  assert.equal(listPublicPhotos().length, 0);
});

test("tag links are unique and moderation history prevents hard deletion", () => {
  const item = db.insert(photos).values(photo(batch().id)).returning().get();
  const tag = db
    .insert(tags)
    .values({ name: "Campus", slug: "campus" })
    .returning()
    .get();
  db.insert(photoTags).values({ photoId: item.id, tagId: tag.id }).run();
  assert.throws(
    () =>
      db.insert(photoTags).values({ photoId: item.id, tagId: tag.id }).run(),
    /UNIQUE/,
  );
  db.insert(moderationLogs)
    .values({
      photoId: item.id,
      adminId: randomUUID(),
      action: "reject",
      fromStatus: "pending",
      toStatus: "rejected",
      note: "Test reason",
    })
    .run();
  assert.throws(
    () => db.delete(photos).where(eq(photos.id, item.id)).run(),
    /FOREIGN KEY/,
  );
});

test("administrator API denies access and submission endpoint reports unavailable", async () => {
  const adminResponse = await getAdminPhotos(
    new Request("http://localhost:3000/api/admin/photos"),
  );
  assert.equal(adminResponse.status, 401);
  assert.deepEqual(await adminResponse.json(), {
    error: { code: "UNAUTHORIZED", message: "请先登录管理员账号。" },
  });
  assert.equal(
    (
      await getAdminReviews(
        new Request("http://localhost:3000/api/admin/reviews"),
      )
    ).status,
    401,
  );
  assert.equal(
    (await submit(new Request("http://localhost:3000/api/submissions"))).status,
    400,
  );
});

test("storage configuration and invalid images fail safely; Turnstile requires configuration", async () => {
  assert.throws(
    () => readStorageEnvironment({ STORAGE_DRIVER: "r2" }),
    /R2_ACCOUNT_ID/,
  );
  await assert.rejects(validateImage(Buffer.from("not an image")), /仅支持/);
  await assert.rejects(verifyTurnstile("not-a-token"), /尚未配置/);
});
